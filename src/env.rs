/// Writes the dotenv `env_file:` names, and returns where it went.
///
/// `Ok(None)` means `env_file: false` — nothing was written and nothing went wrong. A relative
/// path resolves inside the worktree, which is the only place a generated file belongs.
pub fn write_env_file(
    config: &CanopyConfig,
    worktree: &Utf8Path,
    table: &EnvTable,
) -> Result<Option<Utf8PathBuf>, EnvError> {
    let Some(relative) = config.env_file.path() else { return Ok(None) };
    let path = worktree.join(relative);
    // `env_file: config/.env` is legal, and the directory may not exist in a fresh worktree.
    let parent = path.parent().unwrap_or(worktree);
    fs::create_dir_all(parent).map_err(|source| EnvError::Write { path: path.clone(), source })?;
    fs::write(&path, table.to_dotenv()).map_err(|source| EnvError::Write { path: path.clone(), source })?;
    Ok(Some(path))
}

