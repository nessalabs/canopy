/// What this worktree is, for the Canopy variables and the `${…}` scopes.
///
/// Borrowed rather than owned: the caller already has all of it, and copying it per service
/// would be the only allocation in the hot path.
#[derive(Debug, Clone, Copy)]
pub struct Facts<'a> {
    pub worktree_name: &'a str,
    pub worktree_path: &'a Utf8Path,
    /// Empty when the worktree is on a detached HEAD.
    pub branch: &'a str,
    pub project: &'a str,
    pub project_path: &'a Utf8Path,
    /// Named port → the number allocated to this worktree.
    pub ports: &'a BTreeMap<String, u16>,
}

/// The project-wide environment: Canopy's facts, `defaults.env`, `env:`, then the caller's
/// overrides. Last layer wins.
pub fn resolve(config: &CanopyConfig, facts: &Facts<'_>, overrides: &BTreeMap<String, String>) -> EnvTable {
    let mut resolver = Resolver::new(facts);
    resolver.layers(config, overrides);
    resolver.table
}

/// The environment one service sees: [`resolve`] with the service's own `env:` on top.
///
/// `None` when the config has no such service — a caller asking for a name that is not there
/// has a different problem than a service with nothing set.
pub fn resolve_service(
    config: &CanopyConfig,
    service: &str,
    facts: &Facts<'_>,
    overrides: &BTreeMap<String, String>,
) -> Option<EnvTable> {
    let spec = config.services.get(service)?;
    let mut resolver = Resolver::new(facts);
    resolver.layers(config, overrides);
    resolver.layer(&spec.env, EnvSource::Service);
    Some(resolver.table)
}

/// Renders `${…}` in arbitrary text — a `run:` command, a health URL, a setup step — against
/// the same scope that produced `table`, so a command and the environment it runs in cannot
/// disagree about what `${ports.web}` means.
pub fn interpolate(text: &str, facts: &Facts<'_>, table: &EnvTable) -> String {
    let mut resolver = Resolver::new(facts);
    resolver.scope.insert("env".to_owned(), table.to_map());
    substitute(text, &resolver.scope)
}

/// Carries the scope alongside the table being built, since each layer is substituted against
/// everything resolved before it.
struct Resolver<'a> {
    scope: Scope,
    table: EnvTable,
    facts: &'a Facts<'a>,
}

impl<'a> Resolver<'a> {
    fn new(facts: &'a Facts<'a>) -> Resolver<'a> {
        let ports = facts.ports.iter().map(|(name, port)| (name.clone(), port.to_string())).collect();
        let worktree = BTreeMap::from([
            ("name".to_owned(), facts.worktree_name.to_owned()),
            ("path".to_owned(), facts.worktree_path.to_string()),
            ("branch".to_owned(), facts.branch.to_owned()),
        ]);
        let project = BTreeMap::from([
            ("name".to_owned(), facts.project.to_owned()),
            ("path".to_owned(), facts.project_path.to_string()),
        ]);
        // No `db` bucket: this crate does not fork databases, so `${db.x.url}` finds no scope
        // and stays visible as an unresolved reference instead of becoming an empty string.
        let scope = Scope::from([
            ("ports".to_owned(), ports),
            ("worktree".to_owned(), worktree),
            ("project".to_owned(), project),
            ("env".to_owned(), BTreeMap::new()),
        ]);
        Resolver { scope, table: EnvTable::default(), facts }
    }

    fn layers(&mut self, config: &CanopyConfig, overrides: &BTreeMap<String, String>) {
        self.canopy_facts();
        self.layer(&config.defaults.env, EnvSource::Defaults);
        self.layer(&config.env, EnvSource::Config);
        self.layer(overrides, EnvSource::Override);
    }

    /// Always present, always overridable by the project: a file that wants `CANOPY_BRANCH` to
    /// mean something else is allowed to say so.
    fn canopy_facts(&mut self) {
        let facts = self.facts;
        let named = [
            ("CANOPY_WORKTREE", facts.worktree_name.to_owned()),
            ("CANOPY_WORKTREE_PATH", facts.worktree_path.to_string()),
            ("CANOPY_BRANCH", facts.branch.to_owned()),
            ("CANOPY_PROJECT", facts.project.to_owned()),
        ];
        // Facts are data, not templates: a branch named `wip/${ports.web}` must arrive in
        // `CANOPY_BRANCH` exactly as git spells it.
        for (key, value) in named {
            self.record(key, value, EnvSource::Canopy);
        }
        for (name, port) in facts.ports {
            self.record(&format!("CANOPY_PORT_{}", upper_snake(name)), port.to_string(), EnvSource::Canopy);
        }
    }

    fn layer(&mut self, map: &BTreeMap<String, String>, source: EnvSource) {
        for (key, raw) in map {
            let value = substitute(raw, &self.scope);
            self.record(key, value, source);
        }
    }

    fn record(&mut self, key: &str, value: String, source: EnvSource) {
        let secret = is_secret(key, &value);
        self.scope.entry("env".to_owned()).or_default().insert(key.to_owned(), value.clone());
        self.table.set(EnvVar { key: key.to_owned(), value, secret, source });
    }
}

