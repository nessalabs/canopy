/// Module-local: writing a dotenv is the only thing here that can fail, and the crate's `Error`
/// does not need a variant for it.
#[derive(Debug, thiserror::Error)]
pub enum EnvError {
    #[error("cannot write {path}: {source}")]
    Write {
        path: Utf8PathBuf,
        #[source]
        source: std::io::Error,
    },
}

