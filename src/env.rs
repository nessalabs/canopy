//! A worktree's environment: `${…}` substitution, the layering order, and the dotenv on disk.
//!
//! Port of `packages/daemon/src/env/config/resolve.ts`. Every rule about *which* value a
//! service ends up seeing lives here and nowhere else, because "why does my service see this?"
//! must have exactly one answer — and because a preview (`canopywt env`) has to show the same
//! table the supervisor will hand to `execve`.
//!
//! Three decisions are worth their reasons up front.
//!
//! **Substitution is single-pass.** What a substitution inserts is never rescanned. Values come
//! from branch names, from the ambient environment and from a `canopy.yaml` several people
//! share; if the result of `${worktree.branch}` were scanned again, a branch called
//! `wip/${db.main.url}` would read someone else's credentials into a variable. One pass makes
//! substituted text data, permanently.
//!
//! **An unresolvable reference is left verbatim, never blanked and never an error.**
//! `${CANOPY_HOME}` and `$(cat secret)` are shell — `run:` goes to `/bin/sh -c`, so they must
//! survive untouched — and `${db.main.url}` names a database fork this crate does not create
//! yet. Blanking turns a typo into an empty connection string that fails a mile downstream;
//! erroring refuses to run a file the daemon runs fine.
//!
//! **Masking is presentation.** [`EnvTable::masked`] exists for a screen and a JSON payload. The
//! dotenv, `--export` and the child's environment carry the real values, because the point of
//! the table is to make a process work.

use std::collections::BTreeMap;
use std::fs;

use camino::{Utf8Path, Utf8PathBuf};
use serde::Serialize;

use crate::config::{CanopyConfig, TemplateRef, template_refs};

/// What [`EnvTable::masked`] shows instead of a secret. Fixed-width on purpose: a mask whose
/// length tracked the value would leak the length.
pub const MASK: &str = "********";

/// Written at the top of every generated dotenv, since the file is overwritten on every
/// provision and hand edits would vanish without a word.
const DOTENV_HEADER: &str = "# generated by canopy — do not edit";

/// Key substrings that make a variable a secret whatever its value looks like.
const SECRET_WORDS: [&str; 8] =
    ["SECRET", "TOKEN", "PASSWORD", "PASSWD", "APIKEY", "API_KEY", "PRIVATE", "CREDENTIAL"];

// ---------------------------------------------------------------------------------------
// Errors
