    #[test]
    fn masking_is_presentation_only() {
        let table = table_of(&[("NODE_ENV", "development"), ("API_TOKEN", "t0ken"), ("DB", "mysql://u:p@h/d")]);
        let masked = table.masked();
        assert_eq!(masked[0].value, "development");
        assert_eq!(masked[1].value, MASK);
        assert_eq!(masked[2].value, MASK);
        assert_eq!(masked[1].key, "API_TOKEN");
        assert!(masked[1].secret);
        assert!(!masked[0].secret);

        // Everything a process actually reads keeps the real value.
        assert_eq!(table.get("API_TOKEN"), Some("t0ken"));
        assert_eq!(table.to_map()["API_TOKEN"], "t0ken");
        assert!(table.to_dotenv().contains("API_TOKEN=t0ken"));
        assert!(table.to_export().contains("export API_TOKEN='t0ken'"));
        assert!(!table.to_dotenv().contains(MASK));
        assert!(!table.to_export().contains(MASK));

        // A mask that is not the value's length; the length is a secret too.
        assert_eq!(MASK.len(), 8);
        let long = table_of(&[("API_TOKEN", "a-very-long-token-indeed")]);
        assert_eq!(long.masked()[0].value, MASK);
    }

