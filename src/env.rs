// Secrets
// ---------------------------------------------------------------------------------------

/// Secret by key convention first, then by credentials sitting in the value.
fn is_secret(key: &str, value: &str) -> bool {
    let upper = key.to_ascii_uppercase();
    SECRET_WORDS.iter().any(|word| upper.contains(word)) || url_with_password(value)
}

/// `scheme://user:password@host` — never printable whatever the key is called, because the
/// interesting half of a database URL is the half in the middle.
///
/// Hand-written rather than a regex: `^[a-z][a-z0-9+.-]*://[^/@\s]*:[^/@\s]+@`.
fn url_with_password(value: &str) -> bool {
    let Some((scheme, rest)) = value.split_once("://") else { return false };
    let mut scheme_bytes = scheme.bytes();
    let Some(first) = scheme_bytes.next() else { return false };
    if !first.is_ascii_alphabetic() {
        return false;
    }
    if !scheme_bytes.all(|b| b.is_ascii_alphanumeric() || matches!(b, b'+' | b'.' | b'-')) {
        return false;
    }
    // Authority ends at the first `@`; a later one (`/path/a@b`) is not userinfo.
    let Some((userinfo, _)) = rest.split_once('@') else { return false };
    if userinfo.chars().any(|c| c == '/' || c.is_whitespace()) {
        return false;
    }
    // A colon with something after it. `postgres://user@host` and `postgres://user:@host` are
    // not credentials worth hiding.
    userinfo.split_once(':').is_some_and(|(_, password)| !password.is_empty())
}

// ---------------------------------------------------------------------------------------
// Substitution
// ---------------------------------------------------------------------------------------

/// The buckets `${scope.name}` resolves against. `env` is live: a later layer can reference an
/// earlier one with `${env.KEY}`.
type Scope = BTreeMap<String, BTreeMap<String, String>>;

/// One reference's value, or `None` to leave it written as it was.
///
/// The grammar has a third segment (`${db.main.url}`) but every bucket here is flat, so the
/// field is a refinement we do not yet have a use for: `${worktree.path.x}` resolves to
/// `worktree.path`, the same fallback the daemon applies. Database forks will be the first
/// scope with real fields, and this is the function that gains the dotted lookup.
fn lookup<'a>(scope: &'a Scope, reference: &TemplateRef) -> Option<&'a str> {
    scope.get(&reference.scope)?.get(&reference.name).map(String::as_str)
}

/// The one `${…}` a chunk contains, if it is a reference at all.
///
/// Delegates to the linter's parser so that a reference the linter reports as unknown is
/// exactly a reference this function would have substituted — one grammar, not two that drift.
fn single_ref(chunk: &str) -> Option<TemplateRef> {
    template_refs(chunk).into_iter().next()
}

/// Replaces every resolvable `${…}` in `text`. Single-pass: the loop resumes *after* the
/// closing brace of the reference it just replaced, never inside what it inserted.
fn substitute(text: &str, scope: &Scope) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(open) = rest.find("${") {
        out.push_str(&rest[..open]);
        let candidate = &rest[open..];
        // No closing brace anywhere: the rest is shell, or a typo. Either way, verbatim.
        let Some(close) = candidate.find('}') else {
            out.push_str(candidate);
            return out;
        };
        let whole = &candidate[..=close];
        match single_ref(whole).and_then(|reference| lookup(scope, &reference)) {
            Some(value) => out.push_str(value),
            None => out.push_str(whole),
        }
        rest = &candidate[close + 1..];
    }
    out.push_str(rest);
    out
}

/// `main-db` → `MAIN_DB`: the shape every generated env key uses.
fn upper_snake(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut in_separator = false;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_uppercase());
            in_separator = false;
        } else if !in_separator {
            // A run of separators collapses: `main--db` is one boundary, not two.
            out.push('_');
            in_separator = true;
        }
    }
    out
}

