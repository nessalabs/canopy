// The table
// ---------------------------------------------------------------------------------------

/// Which layer had the last word on a variable. Kept per variable rather than recomputed,
/// because the answer to "why is this value what it is" is the layer, not the value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum EnvSource {
    /// Canopy's own facts: `CANOPY_WORKTREE`, `CANOPY_PORT_*`, …
    Canopy,
    /// `defaults.env` in `canopy.yaml`.
    Defaults,
    /// Top-level `env:` in `canopy.yaml`.
    Config,
    /// Handed in by the caller — a `--env` flag, a saved per-worktree setting.
    Override,
    /// A service's own `env:`.
    Service,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct EnvVar {
    pub key: String,
    /// Already substituted. No consumer should ever see a `${…}` it is expected to resolve.
    pub value: String,
    pub secret: bool,
    pub source: EnvSource,
}

/// The resolved environment, in the order the keys first appeared.
///
/// Insertion order, not sorted order, because it reads as the layering: Canopy's facts, then
/// the file, then the overrides. A later layer overwriting a key updates it in place rather
/// than moving it to the end, so the table does not reshuffle when someone adds an override.
/// Anything written to disk sorts instead — see [`EnvTable::to_dotenv`].
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize)]
#[serde(transparent)]
pub struct EnvTable {
    vars: Vec<EnvVar>,
}

impl EnvTable {
    pub fn get(&self, key: &str) -> Option<&str> {
        self.vars.iter().find(|var| var.key == key).map(|var| var.value.as_str())
    }

    pub fn vars(&self) -> &[EnvVar] {
        &self.vars
    }

    /// The table as a plain map, ready for a process spawn.
    pub fn to_map(&self) -> BTreeMap<String, String> {
        self.vars.iter().map(|var| (var.key.clone(), var.value.clone())).collect()
    }

    /// The table with secret values replaced by [`MASK`] — for a terminal or a JSON payload.
    ///
    /// A separate method rather than a flag on the table: masking that could be forgotten on
    /// the way *in* would corrupt what we write to disk. This way the stored value is always
    /// the real one and only the caller that is about to display something asks for the mask.
    pub fn masked(&self) -> Vec<EnvVar> {
        self.vars
            .iter()
            .map(|var| if var.secret { EnvVar { value: MASK.to_owned(), ..var.clone() } } else { var.clone() })
            .collect()
    }

    /// The generated dotenv, byte-for-byte deterministic.
    ///
    /// Sorted by key so the same inputs produce the same file no matter what order the caller
    /// assembled them in: the file lands in a worktree that may be under version control and
    /// is rewritten on every provision, and a diff that is sometimes a reshuffle is a diff
    /// nobody reads.
    pub fn to_dotenv(&self) -> String {
        let mut out = String::from(DOTENV_HEADER);
        out.push('\n');
        for (key, value) in self.to_map() {
            out.push_str(&key);
            out.push('=');
            out.push_str(&dotenv_value(&value));
            out.push('\n');
        }
        out
    }

    /// `export K='v'` lines for `eval "$(canopywt env --export)"`.
    ///
    /// Always single-quoted, even when the dotenv would not bother: this text is fed straight
    /// to a shell, so there is no reader to be lenient for and nothing to gain from bareness.
    pub fn to_export(&self) -> String {
        let mut out = String::new();
        for (key, value) in self.to_map() {
            out.push_str("export ");
            out.push_str(&key);
            out.push('=');
            out.push_str(&single_quote(&value));
            out.push('\n');
        }
        out
    }

    /// Last layer wins, but the key keeps the position it first had.
    fn set(&mut self, var: EnvVar) {
        match self.vars.iter_mut().find(|existing| existing.key == var.key) {
            Some(existing) => *existing = var,
            None => self.vars.push(var),
        }
    }
}

// ---------------------------------------------------------------------------------------
// Quoting
// ---------------------------------------------------------------------------------------

/// Bytes that mean only themselves to `sh` in a value, so a value made of them alone needs no
/// quotes. Everything else — whitespace, `#`, quotes, `$`, backtick, `\`, `~`, `*`, a newline,
/// any non-ASCII byte — gets quoted rather than escaped case by case.
fn is_bare_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-' | b'.' | b'/' | b':' | b'@' | b'%' | b'+' | b',' | b'=')
}

fn needs_quoting(value: &str) -> bool {
    // Empty is the one special case: `KEY=` already assigns an empty string, in both `sh` and
    // every dotenv reader, and `KEY=''` only looks like a value someone forgot to fill in.
    !value.is_empty() && !value.bytes().all(is_bare_byte)
}

/// Single quotes, not double: inside double quotes `sh` still expands `$x`, `` `x` `` and `\`,
/// so `. .env.canopy` would not reproduce the value we resolved. Single quotes are literal all
/// the way through, including newlines.
fn single_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

fn dotenv_value(value: &str) -> String {
    if needs_quoting(value) { single_quote(value) } else { value.to_owned() }
}

